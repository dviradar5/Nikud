"""Build the offline Biblical fallback from an Open Scriptures Hebrew Bible checkout."""

import argparse
from collections import Counter, defaultdict
from pathlib import Path
import re
import unicodedata
import xml.etree.ElementTree as ET


OSIS = "{http://www.bibletechnologies.net/2003/OSIS/namespace}"
MARKS = "\u05b0-\u05bc\u05c1\u05c2\u05c7"
ACCENTS = re.compile("[\u0591-\u05af\u05bd\u05bf\u05c4\u05c5]")
LETTERS = re.compile(f"[א-ת{MARKS}]+")
REMOVE_MARKS = re.compile(f"[{MARKS}]")


def extract(directory):
    counts = defaultdict(Counter)
    books = defaultdict(set)
    for file in sorted(directory.glob("*.xml")):
        for verse in ET.parse(file).iter(OSIS + "verse"):
            words = verse.findall(OSIS + "w")
            seen = set()
            # Skip the final word, where pausal vowels are common.
            for word in words[:-1]:
                morph = word.get("morph", "")
                form = word.text or ""
                # Only Hebrew content words. Keep prefixed and proper-name readings out.
                if not morph.startswith(("HNc", "HV", "HAa", "HD")) or "/" in morph or "/" in form:
                    continue
                form = unicodedata.normalize("NFC", ACCENTS.sub("", form).replace("\u05ba", "\u05b9"))
                if not LETTERS.fullmatch(form):
                    continue
                spelling = REMOVE_MARKS.sub("", form)
                if len(spelling) < 3 or spelling == form:
                    continue
                seen.add((spelling, form))
            for spelling, form in seen:
                counts[spelling][form] += 1
                books[form].add(file.stem)
    return {
        spelling: tuple(form for form, count in sorted(forms.items(), key=lambda item: (-item[1], item[0]))
                        if count >= 3 and len(books[form]) >= 2)
        for spelling, forms in sorted(counts.items())
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("wlc", type=Path, help="Path to morphhb/wlc")
    args = parser.parse_args()
    entries = {spelling: forms for spelling, forms in extract(args.wlc).items() if forms}
    if not entries:
        parser.error("No qualifying forms found. Supply the morphhb/wlc directory.")
    target = Path(__file__).with_name("biblical_forms.py")
    rows = [
        '"""Pointed forms from the Open Scriptures Hebrew Bible (CC BY 4.0).',
        '',
        'Original work of the Open Scriptures Hebrew Bible available at',
        'https://github.com/openscriptures/morphhb. Generated by build_biblical_forms.py.',
        '"""',
        "",
        "FORMS = {",
        *(f"    {spelling!r}: {forms!r}," for spelling, forms in entries.items()),
        "}",
    ]
    target.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"Wrote {len(entries)} spellings and {sum(map(len, entries.values()))} readings.")


if __name__ == "__main__":
    main()
